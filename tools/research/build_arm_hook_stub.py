"""Generate the checked-in trampoline stub bytes from the assembled ARM object.

The canonical stub source is tools/native_camera/hook/a6400_debug_hook_stub.S.
This tool assembles nothing itself; it validates the produced object, rejects
relocations inside the stub (every absolute address is a literal slot filled by
the installer), and emits src/a6400/debug/arm_hook_stub.py so the Unicorn proof
suite runs without a cross toolchain.
"""
import argparse
import hashlib
import json
from pathlib import Path

from elftools.elf.elffile import ELFFile
from elftools.elf.sections import SymbolTableSection

ROOT = Path(__file__).resolve().parents[2]
SECTION = '.text.a6400_hook_stub'
RECORD_WORDS = 24
DEFAULT_OBJECT = ROOT / 'artifacts/native/arm-hook-e0401/a6400_debug_hook_stub.o'
OUTPUT = ROOT / 'src/a6400/debug/arm_hook_stub.py'
SOURCE = ROOT / 'tools/native_camera/hook/a6400_debug_hook_stub.S'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--object', type=Path, default=DEFAULT_OBJECT)
    parser.add_argument('--output', type=Path, default=OUTPUT)
    args = parser.parse_args()
    raw = args.object.read_bytes()
    with args.object.open('rb') as handle:
        elf = ELFFile(handle)
        if elf.header.e_machine != 'EM_ARM' or not elf.little_endian:
            raise SystemExit('stub object is not little-endian ARM')
        section = elf.get_section_by_name(SECTION)
        if section is None:
            raise SystemExit(f'missing section {SECTION}')
        for relocation in elf.iter_sections():
            if relocation.name.startswith('.rel') or relocation.name.startswith('.rela'):
                for target in getattr(relocation, 'iter_relocations', lambda: [])():
                    if target['r_info_sym'] is not None:
                        raise SystemExit(f'unexpected relocation in {relocation.name}; '
                                         'the stub must be relocation-free')
        symbols = {}
        entry_symbols = []
        for name in ('.symtab',):
            table = elf.get_section_by_name(name)
            if isinstance(table, SymbolTableSection):
                for symbol in table.iter_symbols():
                    if not symbol.name or symbol['st_shndx'] == 'SHN_UNDEF':
                        continue
                    if symbol['st_value'] < section['sh_addr']:
                        continue
                    if symbol['st_value'] >= section['sh_addr'] + section['sh_size']:
                        continue
                    offset = symbol['st_value'] - section['sh_addr']
                    symbols[symbol.name] = offset
                    if symbol['st_info']['type'] == 'STT_FUNC':
                        entry_symbols.append(symbol.name)
        code = section.data()
    required = ['a6400_hook_stub', 'a6400_hook_saved_instruction',
                'a6400_hook_ring_next_slot', 'a6400_hook_ring_base_slot',
                'a6400_hook_ring_limit_slot', 'a6400_hook_seq_slot',
                'a6400_hook_ticks_slot', 'a6400_hook_config_slot',
                'a6400_hook_magic_slot', 'a6400_hook_exec_slot',
                'a6400_hook_target_next_slot']
    missing = [name for name in required if name not in symbols]
    if missing:
        raise SystemExit(f'missing stub symbols: {missing}')
    if len(code) % 4:
        raise SystemExit('stub section is not word aligned')
    if symbols['a6400_hook_stub'] != 0:
        raise SystemExit('stub entry is not the first word of the section')
    module = [
        '"""Generated ARM trampoline bytes for the a6400 runtime probe (E0401).',
        '',
        'Generated by tools/research/build_arm_hook_stub.py from',
        'tools/native_camera/hook/a6400_debug_hook_stub.S. Do not edit by hand.',
        '',
        f'source_sha256={hashlib.sha256(SOURCE.read_bytes()).hexdigest()}',
        f'object_sha256={hashlib.sha256(raw).hexdigest()}',
        f'stub_sha256={hashlib.sha256(code).hexdigest()}',
        '"""',
        f'RECORD_WORDS = {RECORD_WORDS}',
        f'RECORD_BYTES = {RECORD_WORDS * 4}',
        f'STUB_SIZE = {len(code)}',
        f'STUB_TEXT = bytes.fromhex("{code.hex()}")',
        'STUB_SYMBOLS = {',
    ]
    for name in required:
        module.append(f'    {name!r}: {symbols[name]},')
    module.append('}')
    module.append('STUB_ENTRY_SYMBOLS = %r' % sorted(entry_symbols))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('\n'.join(module) + '\n', encoding='utf-8')
    receipt = {'object': str(args.object), 'object_sha256': hashlib.sha256(raw).hexdigest(),
               'section': SECTION, 'stub_bytes': len(code),
               'stub_sha256': hashlib.sha256(code).hexdigest(),
               'symbols': symbols, 'output': str(args.output)}
    receipt_path = args.object.with_suffix('.json')
    receipt_path.write_text(json.dumps(receipt, indent=2), encoding='utf-8')
    print(receipt_path)
    print(json.dumps({k: receipt[k] for k in ('stub_bytes', 'stub_sha256')}, indent=2))


if __name__ == '__main__':
    main()
